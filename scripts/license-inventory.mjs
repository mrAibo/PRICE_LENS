import {readFile, writeFile} from "node:fs/promises";
import {fileURLToPath} from "node:url";
import {dirname, resolve} from "node:path";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const lockPath = resolve(root, "package-lock.json");
const inventoryPath = resolve(root, "docs", "DEPENDENCY_LICENSES.md");

const PRODUCTION_REVIEWED_LICENSES = new Set([
  "MIT"
]);

const DEVELOPMENT_REVIEWED_LICENSES = new Set([
  "Apache-2.0",
  "BSD-2-Clause",
  "BSD-3-Clause",
  "BlueOak-1.0.0",
  "CC0-1.0",
  "ISC",
  "MIT",
  "MIT-0",
  "MPL-2.0"
]);

const lock = JSON.parse(await readFile(lockPath, "utf8"));
const packages = [];

for (const [path, metadata] of Object.entries(lock.packages ?? {})) {
  if (!path.includes("node_modules/") || metadata.link === true) continue;

  const name = packageNameFromLockPath(path);
  const version = typeof metadata.version === "string" ? metadata.version : "";
  const license = typeof metadata.license === "string" ? metadata.license.trim() : "";
  const dev = metadata.dev === true;

  if (!name || !version || !license) {
    throw new Error(
      `Dependency metadata is incomplete for ${path}: name=${name || "<missing>"} version=${version || "<missing>"} license=${license || "<missing>"}`
    );
  }

  packages.push({name, version, license, dev});
}

packages.sort((a, b) =>
  a.name.localeCompare(b.name) ||
  a.version.localeCompare(b.version) ||
  a.license.localeCompare(b.license)
);

const production = packages.filter((dependency) => !dependency.dev);
const development = packages.filter((dependency) => dependency.dev);

const unreviewedProduction = production.filter(
  (dependency) => !PRODUCTION_REVIEWED_LICENSES.has(dependency.license)
);
const unreviewedDevelopment = development.filter(
  (dependency) => !DEVELOPMENT_REVIEWED_LICENSES.has(dependency.license)
);

if (unreviewedProduction.length > 0 || unreviewedDevelopment.length > 0) {
  const failures = [
    ...unreviewedProduction.map(
      (dependency) =>
        `production ${dependency.name}@${dependency.version}: ${dependency.license}`
    ),
    ...unreviewedDevelopment.map(
      (dependency) =>
        `development ${dependency.name}@${dependency.version}: ${dependency.license}`
    )
  ];

  throw new Error(
    [
      "Unreviewed dependency license(s) detected.",
      ...failures.map((failure) => `- ${failure}`),
      "Review the dependency and its distribution obligations before extending the allowlist."
    ].join("\n")
  );
}

const inventory = renderInventory(production, development);
const mode = process.argv[2] ?? "--print";

if (mode === "--write") {
  await writeFile(inventoryPath, inventory, "utf8");
  process.stdout.write(`Wrote ${inventoryPath}\n`);
} else if (mode === "--check") {
  const current = await readFile(inventoryPath, "utf8");
  if (current !== inventory) {
    throw new Error(
      "docs/DEPENDENCY_LICENSES.md is stale. Run: npm run licenses:write"
    );
  }
  process.stdout.write(
    `Dependency license gate passed: ${production.length} production + ${development.length} development packages.\n`
  );
} else if (mode === "--print") {
  process.stdout.write(inventory);
} else {
  throw new Error(`Unknown mode: ${mode}`);
}

function packageNameFromLockPath(path) {
  const marker = "node_modules/";
  const index = path.lastIndexOf(marker);
  if (index < 0) return "";

  const tail = path.slice(index + marker.length);
  const parts = tail.split("/");
  return tail.startsWith("@") ? parts.slice(0, 2).join("/") : parts[0];
}

function renderInventory(productionDependencies, developmentDependencies) {
  const devCounts = new Map();
  for (const dependency of developmentDependencies) {
    devCounts.set(
      dependency.license,
      (devCounts.get(dependency.license) ?? 0) + 1
    );
  }

  const productionRows = productionDependencies
    .map(
      (dependency) =>
        `| \`${dependency.name}\` | \`${dependency.version}\` | \`${dependency.license}\` |`
    )
    .join("\n");

  const developmentRows = [...devCounts.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([license, count]) => `| \`${license}\` | ${count} |`)
    .join("\n");

  return `# Dependency License Inventory

Generated from \`package-lock.json\` by \`scripts/license-inventory.mjs\`.
Do not edit this file by hand; run \`npm run licenses:write\`.

## Production npm dependencies

External npm packages reachable from non-development lockfile entries: **${productionDependencies.length}**.

Workspace links are excluded from this table. The vendored \`product-matcher\` source is
tracked separately in \`THIRD_PARTY_NOTICES.md\`.

| Package | Version | License |
| --- | --- | --- |
${productionRows}

The production allowlist is deliberately narrow. A new production license must be
reviewed before \`scripts/license-inventory.mjs\` is changed to accept it.

## Development-only npm dependencies

External development packages in the lockfile: **${developmentDependencies.length}**.

These packages are used for building, testing and typechecking and are not copied into
the pruned production API image as application dependencies.

| License expression | Package count |
| --- | ---: |
${developmentRows}

The development allowlist records licenses already reviewed for tooling use. An unknown
license fails CI and requires explicit review.

## Release policy

- \`package-lock.json\` is committed and CI uses \`npm ci\`.
- The production Docker build also installs from the committed lockfile.
- Missing external-package license metadata fails the gate.
- Any new production license outside the reviewed production allowlist fails the gate.
- Any new development license outside the reviewed development allowlist fails the gate.
- Vendored/copied source remains governed by \`THIRD_PARTY_NOTICES.md\` and
  \`docs/OPEN_SOURCE_REUSE.md\`; this npm inventory does not replace source-level notices.
- Passing this automated check is a release-control signal, not a legal opinion.

## Current vendored source

\`packages/product-matcher/\` is a pinned MIT upstream snapshot. Its upstream commit,
copyright and retained license are documented in \`THIRD_PARTY_NOTICES.md\`.
`;
}
